import assert from 'node:assert/strict';
import {FOREIGN_COUNTRIES} from './data.js';
import {freshState,simulateMatch} from './engine.js';
import {ensureEcosystem,inspectAcademy,createYouthLeague,simulateYouthLeagueRound,createYouthMatch,youthTrain,promoteProspect} from './ecosystem.js';
import {sendYouthScout,advanceYouthScouting,scoutingMissions,signYouthCandidate,startYouthGraduate,youthProgress} from './youth-scouting.js';

const s=ensureEcosystem(freshState()),club='Unión Popular Aurena',country=FOREIGN_COUNTRIES[0];
const historical=s.fixtures.filter(m=>m.legacy&&m.round<=6).map(m=>[m.id,m.scoreH,m.scoreA]);
const t=s.teams[club];
inspectAcademy(s,club);const before=t.budget;
const mission=sendYouthScout(s,club,country);
assert.notEqual(country,t.country);
assert.equal(t.budget,+(before-mission.cost).toFixed(3));
assert.throws(()=>sendYouthScout(s,club,t.country),/otro país/);
assert.deepEqual(advanceYouthScouting(s,'scout-test-1'),[]);
assert.deepEqual(advanceYouthScouting(s,'scout-test-1'),[],'Una fecha no avanza dos veces');
advanceYouthScouting(s,'scout-test-2');
const finished=advanceYouthScouting(s,'scout-test-3');
assert.equal(finished.length,1);
assert.equal(mission.status,'ready');
assert.ok(mission.candidates.length>=4);
const candidate=mission.candidates[0];assert.ok(candidate.pot>candidate.ovr&&candidate.pot<=98);
const beforeHire=t.budget,star=signYouthCandidate(s,club,candidate.id);
assert.equal(t.budget,+(beforeHire-candidate.fee).toFixed(3));
assert.equal(star.nationality,country);
assert.ok(t.youth.some(p=>p.id===star.id));
assert.throws(()=>signYouthCandidate(s,club,candidate.id),/ya fue fichada/);

const original=star.ovr;
for(let i=0;i<8;i++)youthTrain(s,club);
assert.throws(()=>youthTrain(s,club),/8 entrenamientos/);
assert.ok(star.ovr>original,'El OVR sube con experiencia de entrenamiento');
assert.ok(star.ovr<=star.pot);
const first=+star.ovr;
const league=createYouthLeague(s,'Veltrania'),home=league.teams[0],juniors=inspectAcademy(s,home),previous=juniors[0].apps;
const fixtures=simulateYouthLeagueRound(s,'Veltrania'),match=fixtures.find(m=>m.home===home||m.away===home);
assert.equal(juniors[0].apps,previous+1);
assert.ok(match.youthRatings.home.length&&match.youthRatings.away.length);
assert.ok(match.youthRatings.home.every(p=>Number.isFinite(p.rating)));
const friend=createYouthMatch(s,club,'Ferroviarios de Ferral');
assert.ok(friend.youthRatings?.home?.length);
assert.ok(youthProgress(star).needed>0);

const promoted=promoteProspect(s,club,star.id);
assert.ok(promoted.academyGraduate);
startYouthGraduate(s,club,promoted.id);
assert.ok(t.players.slice(0,11).some(p=>p.id===promoted.id));
const nextMatch=s.fixtures.find(m=>!m.played&&(m.home===club||m.away===club));
simulateMatch(s,nextMatch);
assert.ok(promoted.apps>=1);
assert.ok(promoted.growth.history.some(x=>x.reason==='Primer equipo'));
assert.ok(promoted.ovr>=first&&promoted.ovr<=promoted.pot);

const copied=JSON.parse(JSON.stringify(s));
assert.ok(scoutingMissions(copied,club).some(m=>m.status==='ready'));
assert.deepEqual(s.fixtures.filter(m=>m.legacy&&m.round<=6).map(m=>[m.id,m.scoreH,m.scoreA]),historical);
console.log('✅ OJEADORES Y FICHAJES INTERNACIONALES · PRESUPUESTO Y GUARDADOS');
console.log('✅ OVR POR ENTRENAMIENTO, PARTIDOS SUB-20 Y TITULARIDAD EN PRIMERA');
console.log('✅ ESTADÍSTICAS INDIVIDUALES Y 78 PARTIDOS HISTÓRICOS SIN ALTERACIONES');
