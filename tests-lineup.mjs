import assert from 'node:assert/strict';
import {freshState,simulateMatch} from './engine.js';
import {FORMATIONS,lineupState,chooseLineup,selectFormation,selectCaptain,optimizeLineup,resetLineup,matchLineup,lineupStrength} from './lineup.js';

const s=freshState(),name='Unión Popular Aurena',t=s.teams[name];
const legacy=s.fixtures.filter(m=>m.legacy&&m.round<=6).map(m=>[m.id,m.scoreH,m.scoreA]);
const roster=t.players.map(p=>p.id);
const base=lineupState(t);
assert.equal(base.starters.length,11);assert.equal(base.bench.length,7);assert.equal(base.reserves.length,4);
assert.equal(t.lineup,undefined,'Las partidas anteriores no necesitan migración');
const anotherKeeper=t.players.find(p=>p.pos==='POR'&&!base.starters.includes(String(p.id)));
const rosterOut=t.players.at(-1);
chooseLineup(s,name,'starters',0,anotherKeeper.id);
chooseLineup(s,name,'bench',3,rosterOut.id);
selectFormation(s,name,'4-2-3-1');
assert.equal(t.formation,'4-2-3-1');
const second=lineupState(t);
selectCaptain(s,name,second.starters[5]);
assert.equal(lineupState(t).captain,second.starters[5]);
assert.throws(()=>selectCaptain(s,name,second.reserves[0]),/debe ser titular/);
assert.equal(new Set([...second.starters,...second.bench,...second.reserves]).size,t.players.length);
assert.deepEqual(t.players.map(p=>p.id),roster,'No se debe reordenar el plantel al editar');
const expected=matchLineup(t);
const strength=lineupStrength(t,expected);
assert.ok(strength>0&&strength<=100);
const m=s.fixtures.find(f=>!f.played&&(f.home===name||f.away===name));
const played=simulateMatch(s,m);
const side=m.home===name?'home':'away';
assert.equal(played.lineups[side][0],anotherKeeper.id);
assert.ok(played.bench[side].includes(rosterOut.id));
assert.equal(played.captains[side],second.starters[5]);
assert.equal(played.coachAtKickoff[side+'Formation'],'4-2-3-1');
assert.ok(t.players.find(p=>p.id===anotherKeeper.id).apps>0);
assert.ok(played.events.filter(e=>e.type==='sub'&&e.side===side).every(e=>played.bench[side].includes(e.p2)));
assert.deepEqual(s.fixtures.filter(m=>m.legacy&&m.round<=6).map(m=>[m.id,m.scoreH,m.scoreA]),legacy);

t.players.find(p=>p.id===anotherKeeper.id).outGames=3;
const replacement=matchLineup(t);
assert.notEqual(replacement.starters[0].id,anotherKeeper.id,'Bajas deben ser sustituidas al inicio');
const auto=optimizeLineup(s,name);
assert.equal(auto.starters.length,11);assert.ok(auto.bench.length===7);
assert.equal(new Set([...auto.starters,...auto.bench,...auto.reserves]).size,t.players.length);
assert.deepEqual(t.players.map(p=>p.id),roster);
resetLineup(s,name);assert.equal(t.lineup,undefined);
const copy=JSON.parse(JSON.stringify(s));chooseLineup(copy,name,'starters',6,copy.teams[name].players[17].id);
assert.equal(lineupState(copy.teams[name]).starters[6],String(copy.teams[name].players[17].id));
console.log('✅ Once, 7 suplentes, reservas, capitán y formaciones');
console.log('✅ Motor del partido respeta la alineación real, OVR, bajas y convocados');
console.log('✅ Sin futbolistas duplicados, sin alterar partidos anteriores ni guardados');
